from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any


@dataclass
class DetectedFrameworkInfo:
    """Structured information about detected repository test framework and conventions."""

    language: str  # "python" | "typescript" | "javascript"
    framework: str  # "pytest" | "unittest" | "vitest" | "jest" | "mocha"
    config_file: str | None
    test_directory: str
    naming_convention: str  # e.g. "test_*.py" | "*.test.ts"
    runner_command: str  # e.g. "pytest" | "npx vitest run"
    is_available: bool  # True if the executable runner is actually present in the environment
    confidence: float  # 0.0 to 1.0
    missing_requirements: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "language": self.language,
            "framework": self.framework,
            "config_file": self.config_file,
            "test_directory": self.test_directory,
            "naming_convention": self.naming_convention,
            "runner_command": self.runner_command,
            "is_available": self.is_available,
            "confidence": round(self.confidence, 2),
            "missing_requirements": self.missing_requirements,
        }


@dataclass
class GeneratedTestCase:
    """An individual proposed test case generated by TestPilot."""

    name: str
    description: str
    test_type: str  # "unit" | "edge_case" | "boundary" | "negative" | "exception" | "regression"
    target_symbol: str | None
    code: str
    is_edge_case: bool = False
    relevance_explanation: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "test_type": self.test_type,
            "target_symbol": self.target_symbol,
            "code": self.code,
            "is_edge_case": self.is_edge_case,
            "relevance_explanation": self.relevance_explanation,
        }


@dataclass
class GeneratedTestSuite:
    """Complete generated test suite pending human review and approval."""

    framework: str
    test_type: str
    target_files: list[str]
    cases: list[GeneratedTestCase]
    requires_approval: bool = True
    suite_id: uuid.UUID | None = None
    status: str = "GENERATED"

    def to_dict(self) -> dict[str, Any]:
        return {
            "suite_id": str(self.suite_id) if self.suite_id else None,
            "framework": self.framework,
            "test_type": self.test_type,
            "target_files": self.target_files,
            "requires_approval": self.requires_approval,
            "status": self.status,
            "cases": [c.to_dict() for c in self.cases],
        }


@dataclass
class IndividualTestResult:
    """Outcome of a single test item within a test run."""

    test_name: str
    status: str  # "PASSED" | "FAILED" | "SKIPPED" | "ERROR"
    duration_ms: int = 0
    failure_message: str | None = None
    traceback: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "test_name": self.test_name,
            "status": self.status,
            "duration_ms": self.duration_ms,
            "failure_message": self.failure_message,
            "traceback": self.traceback,
        }


@dataclass
class TestExecutionSummary:
    """Detailed result summary of a controlled test execution run."""

    execution_id: uuid.UUID
    suite_id: uuid.UUID | None
    command: str
    status: str  # "PASSED" | "FAILED" | "ERROR" | "TIMED_OUT" | "CANCELLED" | "BLOCKED"
    exit_code: int | None
    stdout: str
    stderr: str
    duration_ms: int
    passed_count: int
    failed_count: int
    skipped_count: int
    results: list[IndividualTestResult] = field(default_factory=list)
    error_message: str | None = None
    executed_at: datetime | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "execution_id": str(self.execution_id),
            "suite_id": str(self.suite_id) if self.suite_id else None,
            "command": self.command,
            "status": self.status,
            "exit_code": self.exit_code,
            "stdout": self.stdout,
            "stderr": self.stderr,
            "duration_ms": self.duration_ms,
            "passed_count": self.passed_count,
            "failed_count": self.failed_count,
            "skipped_count": self.skipped_count,
            "results": [r.to_dict() for r in self.results],
            "error_message": self.error_message,
            "executed_at": self.executed_at.isoformat() if self.executed_at else None,
        }


@dataclass
class DiagnosisReport:
    """Root-cause analysis and actionable suggestions for a failed test run."""

    failing_test: str
    error_message: str
    traceback_parsed: dict[str, Any]
    root_cause_analysis: str
    fix_suggestions: list[str]
    affected_files: list[str]
    confidence: float
    target_symbol: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "failing_test": self.failing_test,
            "error_message": self.error_message,
            "traceback_parsed": self.traceback_parsed,
            "root_cause_analysis": self.root_cause_analysis,
            "fix_suggestions": self.fix_suggestions,
            "affected_files": self.affected_files,
            "confidence": round(self.confidence, 2),
            "target_symbol": self.target_symbol,
        }


@dataclass
class CoverageReportSummary:
    """Parsed test coverage intelligence for a repository."""

    line_coverage_pct: float | None
    branch_coverage_pct: float | None
    uncovered_files: list[str] = field(default_factory=list)
    uncovered_functions: list[dict[str, Any]] = field(default_factory=list)
    is_available: bool = True
    provider: str = "coverage.py"
    raw_report: dict[str, Any] | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "line_coverage_pct": self.line_coverage_pct,
            "branch_coverage_pct": self.branch_coverage_pct,
            "uncovered_files": self.uncovered_files,
            "uncovered_functions": self.uncovered_functions,
            "is_available": self.is_available,
            "provider": self.provider,
        }


@dataclass
class ImpactTestSelectionResult:
    """Targeted regression test selection from ImpactMind change analysis."""

    selected_tests: list[dict[str, Any]]
    impacted_symbols: list[str]
    risk_exposure_score: float  # Structural change exposure metric
    change_summary: str
    rationale: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "selected_tests": self.selected_tests,
            "impacted_symbols": self.impacted_symbols,
            "risk_exposure_score": round(self.risk_exposure_score, 2),
            "change_summary": self.change_summary,
            "rationale": self.rationale,
        }

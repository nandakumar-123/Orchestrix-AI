from __future__ import annotations

import logging
import posixpath
import re
from dataclasses import dataclass, field
from typing import Any

from app.db.models.repository_intelligence import CodeSymbol
from app.services.code_intelligence import PARSER_REGISTRY, ExtractedSymbol, analyze_code_content
from app.services.impactmind.diff_parser import FileDiff, ParsedDiffResult

logger = logging.getLogger("orchestrix.impactmind.ast_classifier")

# Regex for common web framework route decorators
ROUTE_PATTERN = re.compile(
    r"""(?:@(?:app|router|api)\.(get|post|put|delete|patch)|(?:app|router)\.(get|post|put|delete|patch))\s*\(\s*["']([^"']+)["']""",
    re.IGNORECASE,
)
TABLE_PATTERN = re.compile(r"""__tablename__\s*=\s*["']([^"']+)["']""", re.IGNORECASE)


@dataclass
class ClassifiedChange:
    """Classified code change generated by the ASTChangeClassifier."""

    category: str
    file_path: str
    symbol_name: str | None = None
    symbol_id: str | None = None
    is_breaking: bool = False
    breaking_reason: str | None = None
    confidence: float = 1.0
    evidence: str | None = None
    status: str = "resolved"  # "resolved" | "partially_resolved" | "unresolved"
    metadata: dict[str, Any] = field(default_factory=dict)


class ASTChangeClassifier:
    """
    AST-aware change classifier using Tree-sitter parser registry.
    Maps changed line ranges from Git diffs to concrete symbols, compares
    AST before and after, detects breaking changes, and assigns categories.
    """

    def __init__(
        self,
        existing_symbols: list[CodeSymbol] | None = None,
        file_contents_before: dict[str, str] | None = None,
        file_contents_after: dict[str, str] | None = None,
    ) -> None:
        self.existing_symbols = existing_symbols or []
        self.file_contents_before = file_contents_before or {}
        self.file_contents_after = file_contents_after or {}

        # Index existing symbols by file path
        self.symbols_by_file: dict[str, list[CodeSymbol]] = {}
        for s in self.existing_symbols:
            self.symbols_by_file.setdefault(s.file_path, []).append(s)

    def classify_diff(self, parsed_diff: ParsedDiffResult) -> list[ClassifiedChange]:
        """Classify all file changes in the parsed git diff."""
        classifications: list[ClassifiedChange] = []
        for file_diff in parsed_diff.files:
            file_changes = self.classify_file_diff(file_diff)
            classifications.extend(file_changes)
        return classifications

    def classify_changes(
        self,
        diff_result: ParsedDiffResult,
        symbols_by_file: dict[str, list[CodeSymbol]] | None = None,
        file_contents_before: dict[str, str] | None = None,
        file_contents_after: dict[str, str] | None = None,
    ) -> list[ClassifiedChange]:
        """Convenience method accepting optional symbol mapping and source text overrides."""
        if symbols_by_file is not None:
            self.symbols_by_file = symbols_by_file
        if file_contents_before is not None:
            self.file_contents_before = file_contents_before
        if file_contents_after is not None:
            self.file_contents_after = file_contents_after
        return self.classify_diff(diff_result)


    def classify_file_diff(self, file_diff: FileDiff) -> list[ClassifiedChange]:
        """Classify changes in a single file diff."""
        path = file_diff.path
        ext = posixpath.splitext(path)[1].lower()

        # 1. Non-code / Documentation / Config classification
        if ext in (".md", ".txt", ".rst", ".adoc"):
            return [
                ClassifiedChange(
                    category="DOCUMENTATION_CHANGE",
                    file_path=path,
                    confidence=1.0,
                    evidence=f"Documentation file modified: {path}",
                    status="resolved",
                )
            ]

        if path.endswith(
            (
                "package.json",
                "pyproject.toml",
                "Cargo.toml",
                "go.mod",
                "pom.xml",
                "requirements.txt",
                "Gemfile",
            )
        ):
            # Inspect diff lines to see if dependencies were modified
            added_text = " ".join(
                line for h in file_diff.hunks for line in h.added_lines
            )
            deleted_text = " ".join(
                line for h in file_diff.hunks for line in h.deleted_lines
            )
            is_breaking = bool(deleted_text.strip())
            return [
                ClassifiedChange(
                    category="DEPENDENCY_CHANGE",
                    file_path=path,
                    is_breaking=is_breaking,
                    breaking_reason="Dependency removed or version constraint altered"
                    if is_breaking
                    else None,
                    confidence=1.0,
                    evidence=f"Dependency manifest modified: +{file_diff.total_additions} -{file_diff.total_deletions}",
                    status="resolved",
                )
            ]

        if ext in (".yaml", ".yml", ".json", ".toml", ".ini", ".env.example", ".conf"):
            return [
                ClassifiedChange(
                    category="CONFIGURATION_CHANGE",
                    file_path=path,
                    confidence=0.95,
                    evidence=f"Configuration file modified: {path}",
                    status="resolved",
                )
            ]

        # 2. Test File classification
        is_test_file = (
            "/tests/" in path
            or path.startswith("tests/")
            or path.endswith(
                (
                    ".test.ts",
                    ".test.js",
                    ".spec.ts",
                    ".spec.js",
                    "_test.go",
                    "_test.py",
                    "test_*.py",
                )
            )
        )

        # 3. Handle file deletion
        if file_diff.change_type == "deleted":
            old_symbols = self.symbols_by_file.get(file_diff.old_path, [])
            results: list[ClassifiedChange] = []
            if not old_symbols:
                category = "TEST_CHANGE" if is_test_file else "PUBLIC_API_CHANGE"
                results.append(
                    ClassifiedChange(
                        category=category,
                        file_path=file_diff.old_path,
                        is_breaking=not is_test_file,
                        breaking_reason=f"File deleted containing potential public symbols: {file_diff.old_path}",
                        confidence=0.9,
                        evidence=f"Deleted file {file_diff.old_path}",
                        status="resolved",
                    )
                )
            else:
                for s in old_symbols:
                    results.append(
                        ClassifiedChange(
                            category="TEST_CHANGE" if is_test_file else "PUBLIC_API_CHANGE",
                            file_path=file_diff.old_path,
                            symbol_name=s.name,
                            symbol_id=str(s.id),
                            is_breaking=not is_test_file,
                            breaking_reason=f"Public symbol '{s.name}' ({s.symbol_type}) deleted with file removal",
                            confidence=1.0,
                            evidence=f"Removed {s.symbol_type} {s.name}",
                            status="resolved",
                        )
                    )
            return results

        # 4. AST Extraction on New / Modified File Content
        new_content = self.file_contents_after.get(path, "")
        old_content = self.file_contents_before.get(file_diff.old_path, "")

        # If full contents not available, classify using existing symbols and diff hunks
        if not new_content and not old_content:
            return self._classify_with_existing_symbols(file_diff, is_test_file)

        # Parse ASTs using Tree-sitter
        lang_name = PARSER_REGISTRY._ext_map.get(ext) or "Python"
        new_analysis = (
            analyze_code_content(new_content.encode("utf-8"), lang_name)
            if new_content
            else None
        )
        old_analysis = (
            analyze_code_content(old_content.encode("utf-8"), lang_name)
            if old_content
            else None
        )

        new_syms = new_analysis.symbols if new_analysis else []
        old_syms = old_analysis.symbols if old_analysis else []

        old_sym_map = {s.name: s for s in old_syms}
        new_sym_map = {s.name: s for s in new_syms}

        results = []
        changed_new_ranges = file_diff.changed_new_line_ranges

        # Check for Removed Symbols (Breaking changes)
        for old_name, old_s in old_sym_map.items():
            if old_name not in new_sym_map:
                is_breaking = not is_test_file and old_s.symbol_type in (
                    "function",
                    "class",
                    "method",
                    "interface",
                )
                results.append(
                    ClassifiedChange(
                        category="TEST_CHANGE" if is_test_file else "PUBLIC_API_CHANGE",
                        file_path=path,
                        symbol_name=old_name,
                        is_breaking=is_breaking,
                        breaking_reason=f"Public symbol '{old_name}' removed from {path}"
                        if is_breaking
                        else None,
                        confidence=0.98,
                        evidence=f"Removed {old_s.symbol_type} {old_name} (was lines {old_s.start_line}-{old_s.end_line})",
                        status="resolved",
                    )
                )

        # Check New and Modified Symbols
        for new_name, new_s in new_sym_map.items():
            # Check if this symbol intersects with any changed line ranges
            sym_range = (new_s.start_line, new_s.end_line)
            intersects = any(
                not (sym_range[1] < r_start or sym_range[0] > r_end)
                for r_start, r_end in changed_new_ranges
            )
            if not intersects and file_diff.change_type != "added":
                continue

            prev_sym = old_sym_map.get(new_name)

            if not prev_sym:
                # Newly Added Symbol
                category = "TEST_CHANGE" if is_test_file else "PUBLIC_API_CHANGE"
                results.append(
                    ClassifiedChange(
                        category=category,
                        file_path=path,
                        symbol_name=new_name,
                        is_breaking=False,
                        confidence=0.95,
                        evidence=f"Added {new_s.symbol_type} {new_name}: {new_s.signature}",
                        status="resolved",
                    )
                )
                continue

            # Symbol exists in both: evaluate modifications
            sig_changed = (prev_sym.signature or "").strip() != (new_s.signature or "").strip()
            body_changed = intersects

            # Check Database Schema Changes
            if "Database" in path or "__tablename__" in new_content or "model" in path.lower():
                tbl_match = TABLE_PATTERN.search(new_content)
                if tbl_match and new_s.symbol_type == "class":
                    results.append(
                        ClassifiedChange(
                            category="DATABASE_SCHEMA_CHANGE",
                            file_path=path,
                            symbol_name=new_name,
                            is_breaking=True,
                            breaking_reason=f"Database model '{new_name}' schema modified; potential migration needed",
                            confidence=0.95,
                            evidence=new_s.signature or f"table: {tbl_match.group(1)}",
                            status="resolved",
                        )
                    )
                    continue

            # Check API Route Changes
            if ROUTE_PATTERN.search(new_content) and new_s.symbol_type in ("function", "method"):
                route_match = ROUTE_PATTERN.search(new_content)
                if route_match:
                    results.append(
                        ClassifiedChange(
                            category="API_ROUTE_CHANGE",
                            file_path=path,
                            symbol_name=new_name,
                            is_breaking=sig_changed,
                            breaking_reason="API route handler signature modified"
                            if sig_changed
                            else None,
                            confidence=0.95,
                            evidence=f"Endpoint route handler {new_name}",
                            status="resolved",
                        )
                    )
                    continue

            # Check Inheritance Changes
            if new_s.symbol_type == "class" and sig_changed:
                if ("(" in (new_s.signature or "") and "(" in (prev_sym.signature or "")) or (
                    "extends" in (new_s.signature or "") or "implements" in (new_s.signature or "")
                ):
                    results.append(
                        ClassifiedChange(
                            category="INHERITANCE_CHANGE",
                            file_path=path,
                            symbol_name=new_name,
                            is_breaking=True,
                            breaking_reason=f"Class '{new_name}' inheritance hierarchy modified",
                            confidence=0.95,
                            evidence=f"Before: {prev_sym.signature} | After: {new_s.signature}",
                            status="resolved",
                        )
                    )
                    continue

            # Signature Change vs Logic Change
            if sig_changed:
                is_breaking = self._is_breaking_signature_change(prev_sym, new_s)
                results.append(
                    ClassifiedChange(
                        category="SIGNATURE_CHANGE",
                        file_path=path,
                        symbol_name=new_name,
                        is_breaking=is_breaking,
                        breaking_reason=f"Signature of '{new_name}' altered: required parameters or return contract modified"
                        if is_breaking
                        else None,
                        confidence=0.95,
                        evidence=f"Before: {prev_sym.signature} | After: {new_s.signature}",
                        status="resolved",
                    )
                )
            elif body_changed:
                results.append(
                    ClassifiedChange(
                        category="TEST_CHANGE" if is_test_file else "LOGIC_CHANGE",
                        file_path=path,
                        symbol_name=new_name,
                        is_breaking=False,
                        confidence=0.90,
                        evidence=f"Internal logic in '{new_name}' updated (lines {new_s.start_line}-{new_s.end_line})",
                        status="resolved",
                    )
                )

        # Check Import Changes
        if new_analysis and old_analysis:
            old_imports = {imp.module_name for imp in old_analysis.imports}
            new_imports = {imp.module_name for imp in new_analysis.imports}
            if old_imports != new_imports:
                added_imp = new_imports - old_imports
                removed_imp = old_imports - new_imports
                results.append(
                    ClassifiedChange(
                        category="IMPORT_CHANGE",
                        file_path=path,
                        is_breaking=bool(removed_imp),
                        breaking_reason=f"Imported modules removed: {', '.join(sorted(removed_imp))}"
                        if removed_imp
                        else None,
                        confidence=0.95,
                        evidence=f"Added: {', '.join(sorted(added_imp))} | Removed: {', '.join(sorted(removed_imp))}",
                        status="resolved",
                    )
                )

        if not results:
            # Fallback change classification
            results.append(
                ClassifiedChange(
                    category="TEST_CHANGE" if is_test_file else "LOGIC_CHANGE",
                    file_path=path,
                    is_breaking=False,
                    confidence=0.80,
                    evidence=f"File content modified: +{file_diff.total_additions} -{file_diff.total_deletions}",
                    status="resolved",
                )
            )

        return results

    def _classify_with_existing_symbols(
        self, file_diff: FileDiff, is_test_file: bool
    ) -> list[ClassifiedChange]:
        """Fallback classification when full source content before/after is absent."""
        path = file_diff.path
        symbols = self.symbols_by_file.get(path, [])
        results: list[ClassifiedChange] = []

        if is_test_file:
            default_cat = "TEST_CHANGE"
        elif any(k in path.lower() for k in ("alembic", "migration", "schema")) or path.endswith((".sql",)):
            default_cat = "DATABASE_SCHEMA_CHANGE"
        elif any(k in path.lower() for k in ("routes", "api", "controllers", "endpoints")):
            default_cat = "API_ROUTE_CHANGE"
        else:
            default_cat = "LOGIC_CHANGE"

        changed_ranges = file_diff.changed_new_line_ranges

        for s in symbols:
            intersects = any(
                not (s.end_line < r_start or s.start_line > r_end)
                for r_start, r_end in changed_ranges
            )
            if intersects:
                results.append(
                    ClassifiedChange(
                        category=default_cat,
                        file_path=path,
                        symbol_name=s.name,
                        symbol_id=str(s.id),
                        is_breaking=False,
                        confidence=0.85,
                        evidence=f"Lines {s.start_line}-{s.end_line} overlap with diff hunks",
                        status="resolved",
                    )
                )

        if not results:
            results.append(
                ClassifiedChange(
                    category=default_cat,
                    file_path=path,
                    is_breaking=False,
                    confidence=0.75,
                    evidence=f"Modified file with {len(file_diff.hunks)} hunks",
                    status="partially_resolved",
                )
            )

        return results

    def _is_breaking_signature_change(
        self, old_s: ExtractedSymbol, new_s: ExtractedSymbol
    ) -> bool:
        """
        Heuristic to determine if a signature change breaks callers.
        - Additional required parameters without defaults -> Breaking.
        - Removed parameters -> Breaking.
        - Return type changed -> Breaking.
        """
        old_sig = (old_s.signature or "").strip()
        new_sig = (new_s.signature or "").strip()

        # If parameter count increased without '=' default marker, likely breaking
        old_params = old_sig[old_sig.find("(") : old_sig.rfind(")")] if "(" in old_sig else ""
        new_params = new_sig[new_sig.find("(") : new_sig.rfind(")")] if "(" in new_sig else ""

        if old_params != new_params:
            # Check if new parameters have default values
            new_param_list = [p.strip() for p in new_params.strip("()").split(",") if p.strip()]
            old_param_list = [p.strip() for p in old_params.strip("()").split(",") if p.strip()]

            # If parameters removed, breaking
            if len(new_param_list) < len(old_param_list):
                return True

            # If new parameters added without default value '=', breaking
            for i in range(len(old_param_list), len(new_param_list)):
                if "=" not in new_param_list[i]:
                    return True

        return False
